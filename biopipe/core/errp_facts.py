def fact_order(n: int, false_rate: float, rng=random):
    """``n`` distinct statements as (text, is_false), shuffled, ``round(n * false_rate)`` false.
    Capped by the pool size (100 of each)."""
    n_false = min(len(FALSE_FACTS), max(0, round(n * false_rate)))
    n_true = min(len(TRUE_FACTS), max(0, n - n_false))
    items = ([(s, True) for s in rng.sample(FALSE_FACTS, n_false)]
             + [(s, False) for s in rng.sample(TRUE_FACTS, n_true)])
    rng.shuffle(items)
    return items
